-- 1. Create PROFILES Table
create table if not exists public.profiles (
  id uuid references auth.users on delete cascade primary key,
  email text,
  monthly_salary numeric default 20000.0,
  daily_expense_target numeric default 500.0,
  monthly_expense_target numeric default 15000.0,
  monthly_savings_target numeric default 5000.0,
  created_at timestamptz default now()
);

-- Enable Row Level Security (RLS) for Profiles
alter table public.profiles enable row level security;

create policy "Users can view own profile" on public.profiles
  for select using (auth.uid() = id);

create policy "Users can insert own profile" on public.profiles
  for insert with check (auth.uid() = id);

create policy "Users can update own profile" on public.profiles
  for update using (auth.uid() = id);

-- 2. Create EXPENSES Table
create table if not exists public.expenses (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users on delete cascade not null default auth.uid(),
  name text not null,
  category text not null,
  amount numeric not null,
  type text not null default 'expense', -- 'expense' or 'income'
  date timestamptz not null default now(),
  is_over_limit boolean default false,
  is_paid boolean default true,
  created_at timestamptz default now()
);

-- Enable Row Level Security (RLS) for Expenses
alter table public.expenses enable row level security;

create policy "Users can manage own expenses" on public.expenses
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

-- 3. Create PRESETS ("Regulars") Table
create table if not exists public.presets (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users on delete cascade not null default auth.uid(),
  name text not null,
  category text not null,
  default_amount numeric not null default 0.0,
  type text not null default 'expense', -- 'expense' or 'income'
  is_auto_add boolean default false,
  auto_add_day integer default 1,
  created_at timestamptz default now()
);

-- Enable Row Level Security (RLS) for Presets
alter table public.presets enable row level security;

create policy "Users can manage own presets" on public.presets
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

-- 4. Create GOALS Table
create table if not exists public.goals (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users on delete cascade not null default auth.uid(),
  name text not null,
  target_cost numeric,
  note text,
  target_date timestamptz,
  status text not null default 'active', -- 'active' or 'done'
  created_at timestamptz default now(),
  completed_at timestamptz
);

-- Enable Row Level Security (RLS) for Goals
alter table public.goals enable row level security;

create policy "Users can manage own goals" on public.goals
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

-- 5. Auto-create Profile row when a user registers
create or replace function public.handle_new_user()
returns trigger as $$
begin
  insert into public.profiles (id, email)
  values (new.id, new.email);
  return new;
end;
$$ language plpgsql security definer;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();
